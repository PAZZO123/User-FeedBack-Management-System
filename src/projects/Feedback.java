    private void submitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submitButtonActionPerformed
        // TODO add your handling code here:

if (!MasterClass.checkEmail(emailField.getText())) {
            JOptionPane.showMessageDialog(this, "Invalid Email! Format: example@domain.com", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (emailField.getText().isEmpty() || firstNameField.getText().isEmpty() ||
                lastNameField.getText().isEmpty() || commentArea.getText().isEmpty()) {
        
            JOptionPane.showMessageDialog(this, "All fields are required!");
            return;
        }



        // Store feedback in ArrayList
        feedbackList.add(new Object[]{
                emailField.getText(),
                firstNameField.getText(),
                lastNameField.getText(),
                commentArea.getText(),
                genderBox.getSelectedItem()
        });

        // Update JTable
        DefaultTableModel model = (DefaultTableModel) dataTable.getModel();
        model.setRowCount(0); // Clear table before adding all feedback again
        for (Object[] row : feedbackList) {
            model.addRow(row);
        }

        JOptionPane.showMessageDialog(this, "Feedback submitted successfully!");

        // Clear input fields for the next submission
        emailField.setText("");
        firstNameField.setText("");
        lastNameField.setText("");
        commentArea.setText("");
    }//GEN-LAST:event_submitButtonActionPerformed

    private void displyButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_displyButtonActionPerformed

// TODO add your handling code here:
 int selectedRow = dataTable.getSelectedRow(); // Get selected row index

    if (selectedRow == -1) { // If no row is selected
        JOptionPane.showMessageDialog(this, "Please select a feedback row to view!", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Retrieve data from selected row
    String email = dataTable.getValueAt(selectedRow, 0).toString();
    String firstName = dataTable.getValueAt(selectedRow, 1).toString();
    String lastName = dataTable.getValueAt(selectedRow, 2).toString();
    String comment = dataTable.getValueAt(selectedRow, 3).toString();
    String gender = dataTable.getValueAt(selectedRow, 4).toString();

    // Open ResultPage with selected data
    ResultPage resultPage = new ResultPage(email, firstName, lastName, comment, gender);
    resultPage.setVisible(true);
    }//GEN-LAST:event_displyButtonActionPerformed
 
